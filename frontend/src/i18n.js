export function translate(lang, text, vars) {
  if (text == null) return "";
  const source = String(text);
  let out = normalizeLang(lang) === "en" ? (EN[source] ?? source) : source;
  if (vars) {
    Object.entries(vars).forEach(([key, value]) => {
      out = String(out).replaceAll(`{${key}}`, String(value));
    });
  }
  return out;
}

export function displayVipName(lang, name) {
  if (!name || name === "بدون VIP") return translate(lang, "بدون VIP");
  return name;
}
