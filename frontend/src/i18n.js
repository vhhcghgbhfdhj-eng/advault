export const LANG_KEY = "advault_lang";

export function normalizeLang(value) {
  return value === "en" ? "en" : "ar";
}

export function readLang() {
  try {
    return normalizeLang(localStorage.getItem(LANG_KEY));
  } catch {
    return "ar";
  }
}

export function applyDocumentLang(lang) {
  const value = normalizeLang(lang);
  if (typeof document === "undefined") return value;
  document.documentElement.lang = value === "en" ? "en" : "ar";
  document.documentElement.dir = value === "en" ? "ltr" : "rtl";
  return value;
}

export function saveLang(lang) {
  const value = normalizeLang(lang);
  localStorage.setItem(LANG_KEY, value);
  applyDocumentLang(value);
  return value;
}

export function formatDate(lang, value) {
  if (!value) return "—";
  return new Date(value).toLocaleString(normalizeLang(lang) === "en" ? "en" : "ar");
}

